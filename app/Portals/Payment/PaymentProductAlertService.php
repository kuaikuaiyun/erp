    /** @param \Illuminate\Database\Query\Builder $disputes */
    private function globalInitialPayPalDisputeAmount($disputes): float
    {
        $database = $this->database();

        return round((float) $database->table('logistics_orders as orders')
            ->leftJoinSub(clone $disputes, 'paypal_disputes', function ($join): void {
                $join->on('paypal_disputes.logistics_order_id', '=', 'orders.id')
                    ->on('paypal_disputes.logistics_paypal_account_id', '=', 'orders.paypal_account_id');
            })
            ->where(function ($query): void {
                $query->whereNull('orders.subscription_origin_order_id')
                    ->orWhereRaw("TRIM(orders.subscription_origin_order_id) = ''");
            })
            ->where(function ($query): void {
                $query->whereNotNull('orders.paid_at')->orWhere('orders.paid_amount_usd', '>', 0);
            })
            ->whereNotNull('orders.paypal_account_id')
            ->where('orders.paypal_association_source', 'actual_transaction')
            ->sum(DB::raw('COALESCE(paypal_disputes.dispute_amount, 0)')), 4);
    }

    /** @param Collection<int,array<string,mixed>> $alerts @return Collection<int,array<string,mixed>> */
    private function withStatuses(Collection $alerts, bool $includeHistory = false): Collection
    {
        if ($alerts->isEmpty()) {
            return $alerts;
        }

        $statuses = PaymentProductAlertAssignment::query()
            ->whereIn('alert_code', $alerts->pluck('code')->all())
            ->get()->keyBy('alert_code');
        $logs = $includeHistory
            ? PaymentProductAlertAssignmentLog::query()
                ->whereIn('alert_code', $alerts->pluck('code')->all())
                ->where('event', 'status_changed')->latest('created_at')->get()->groupBy('alert_code')
            : collect();

        return $alerts->map(function (array $alert) use ($statuses, $logs): array {
            $record = $statuses->get($alert['code']);
            $history = collect($logs->get($alert['code'], collect()))->map(function (PaymentProductAlertAssignmentLog $log): array {
                $payload = json_decode((string) $log->note, true);
                $status = is_array($payload) ? (string) ($payload['to_status'] ?? 'pending') : 'pending';
                $status = $this->normaliseResultStatus($status);
                return [
                    'status' => $status,
                    'remark' => is_array($payload) ? (string) ($payload['remark'] ?? '') : (string) $log->note,
                    'actor' => (string) ($log->actor_name_snapshot ?: '-'),
                    'time' => $log->created_at ? $log->created_at->timezone('Asia/Shanghai')->format('Y-m-d H:i:s') : '-',
                ];
            })->values()->all();
            $alert['status_history'] = $history;
            $alert['latest_remark'] = (string) ($history[0]['remark'] ?? '');
            if (!$record) {
                return $alert;
            }

            $alert['status_key'] = $this->normaliseResultStatus((string) $record->status);
            $alert['workflow_status_key'] = $this->workflowStatus($alert['status_key']);
            $alert['action_key'] = 'view';
            return $alert;
        });
    }

    /** @return Collection<int,array<string,mixed>> */
    private function alertRows(): Collection
    {
        $rows = $this->cachedMetricRows(false);
        $historicalCodes = PaymentProductAlertAssignment::query()->pluck('alert_code')->flip();

        return $this->withStatuses($rows->filter(
            fn (array $row): bool => (bool) ($row['is_alert'] ?? false) || $historicalCodes->has($row['code'])
        )->values());
    }

    /** @return Collection<int,array<string,mixed>> */
    private function cachedMetricRows(bool $onlyQualified = true, array $productKeys = [], array $filters = []): Collection
    {
        $productKeys = array_values(array_unique(array_filter(array_map(
            static fn (mixed $value): string => trim((string) $value),
            $productKeys,
        ))));
        sort($productKeys);

        $metricFilters = [
            'date_from' => (string) ($filters['date_from'] ?? ''),
            'date_to' => (string) ($filters['date_to'] ?? ''),
            'date_mode' => (string) ($filters['date_mode'] ?? 'order'),
            'store' => (string) ($filters['store'] ?? ''),
        ];
        $cacheKey = 'payment:product-alert-metrics:v3:'.sha1((string) json_encode([
            'qualified' => $onlyQualified,
            'products' => $productKeys,
            'filters' => $metricFilters,
        ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES));

        $rows = Cache::flexible(
            $cacheKey,
            [self::METRIC_CACHE_SECONDS, self::METRIC_CACHE_STALE_SECONDS],
            fn (): array => $this->metricRows($onlyQualified, $productKeys, $metricFilters)->values()->all(),
        );

        return collect($rows);
    }

    /** @param array<string,mixed> $filters */
    private function applyOrderPaidAtRange(object $query, array $filters, string $column = 'orders.paid_at'): void
    {
        $from = trim((string) ($filters['date_from'] ?? ''));
        $to = trim((string) ($filters['date_to'] ?? ''));
        if ($from !== '') {
            $query->where($column, '>=', Carbon::parse($from)->startOfDay()->toDateTimeString());
        }
        if ($to !== '') {
            $query->where($column, '<', Carbon::parse($to)->addDay()->startOfDay()->toDateTimeString());
        }
    }

    /** @return array<string,mixed>|null */
    private function findAlertRow(string $alertCode, bool $includeHistory = false): ?array
    {
        if (!preg_match('/^PW-(?:([PC])-)?(\d+)$/', $alertCode, $matches)) {
            return null;
        }

        $itemId = (int) $matches[2];
        $channel = ($matches[1] ?? '') === 'C' ? 'credit_card' : (($matches[1] ?? '') === 'P' ? 'paypal' : '');
        $productKeyExpression = $this->productKeyExpression('alert_item');
        $item = $this->database()->table('logistics_order_items as alert_item')
            ->where('alert_item.id', $itemId)
            ->selectRaw("{$productKeyExpression} as product_key")
            ->first();
        $productKey = trim((string) ($item->product_key ?? ''));
        if ($productKey === '') {
            return null;
        }

        $row = $this->cachedMetricRows(false, [$productKey])
            ->first(function (array $candidate) use ($alertCode, $channel): bool {
                if ($channel !== '' && (string) ($candidate['channel_type'] ?? '') !== $channel) {
                    return false;
                }

                return hash_equals((string) ($candidate['code'] ?? ''), $alertCode);
            });
        if (!is_array($row)) {
            return null;
        }

        $isHistorical = PaymentProductAlertAssignment::query()->where('alert_code', $alertCode)->exists();
        if (!(bool) ($row['is_alert'] ?? false) && !$isHistorical) {
            return null;
        }

        return $this->withStatuses(collect([$row]), $includeHistory)->first();
    }

    /**
     * @param Collection<int,array<string,mixed>> $alerts
     * @param array<string,mixed> $filters
     * @return Collection<int,array<string,mixed>>
     */
    private function filterRows(Collection $alerts, array $filters): Collection
    {
        $flowStatus = trim((string) ($filters['flow_status'] ?? 'open'));
        $processingStatus = trim((string) ($filters['processing_status'] ?? ''));
        $product = mb_strtolower(trim((string) ($filters['product'] ?? '')));
        $channel = trim((string) ($filters['channel'] ?? ''));
        $severity = trim((string) ($filters['severity'] ?? ''));
        $sample = trim((string) ($filters['sample'] ?? ''));

        return $alerts->filter(function (array $row) use ($flowStatus, $processingStatus, $product, $channel, $severity, $sample): bool {
            if ($flowStatus === 'open' && $row['workflow_status_key'] === 'completed') {
                return false;
            }
            if ($flowStatus === 'completed' && $row['workflow_status_key'] !== 'completed') {
                return false;
            }
            if ($processingStatus !== '' && $row['status_key'] !== $processingStatus) {
                return false;
            }
            if ($product !== '') {
                $search = mb_strtolower(implode(' ', [$row['product_name'], $row['source_product_name'], $row['sku']]));
                if (!str_contains($search, $product)) {
                    return false;
                }
            }
            if ($channel !== '' && ($row['channel_type'] ?? '') !== $channel) {
                return false;
            }
            if ($severity !== '' && ($row['severity_key'] ?? '') !== $severity) {
                return false;
            }
            $count = (int) ($row['eligible_order_count'] ?? 0);
            if ($sample === 'under_50' && $count >= 50) return false;
            if ($sample === '50_500' && ($count < 50 || $count > 500)) return false;
            if ($sample === 'over_500' && $count <= 500) return false;
            return true;
        })->values();
    }

    private function normaliseResultStatus(string $status): string
    {
        return match ($status) {
            'stopped', 'observing', 'backend_optimized', 'other', 'completed', 'processing' => $status,
            default => 'pending',
        };
    }

    private function workflowStatus(string $status): string
    {
        return match ($status) {
            'completed' => 'completed',
            'stopped', 'observing', 'backend_optimized', 'other', 'processing' => 'processing',
            default => 'pending',
        };
    }

    private function formatDateTime(mixed $value): string
    {
        return $value ? Carbon::parse((string) $value, 'UTC')->timezone('Asia/Shanghai')->format('Y-m-d H:i') : '-';
    }

    /** Credit-card records intentionally remain on the order-payment cohort. */
    private function applyPayPalEventDateFilters(object $query, array $filters, string $column): void
    {
        if (($filters['date_mode'] ?? 'order') !== 'event') {
            return;
        }
        if (trim((string) ($filters['date_from'] ?? '')) !== '') {
            $query->where($column, '>=', Carbon::parse($filters['date_from'], 'Asia/Shanghai')->startOfDay()->utc()->toDateTimeString());
        }
        if (trim((string) ($filters['date_to'] ?? '')) !== '') {
            $query->where($column, '<=', Carbon::parse($filters['date_to'], 'Asia/Shanghai')->endOfDay()->utc()->toDateTimeString());
        }
    }

    private function productKeyExpression(string $alias): string
    {
        return "CASE "
            ."WHEN NULLIF(TRIM({$alias}.tongtu_product_code), '') IS NOT NULL THEN CONCAT('tongtu-product-code:', LOWER(TRIM({$alias}.tongtu_product_code))) "
            ."WHEN NULLIF(TRIM({$alias}.shopify_sku), '') IS NOT NULL THEN CONCAT('shopify-sku:', LOWER(TRIM({$alias}.shopify_sku))) "
            ."WHEN NULLIF(TRIM({$alias}.tongtu_sku), '') IS NOT NULL THEN CONCAT('tongtu-sku:', LOWER(TRIM({$alias}.tongtu_sku))) "
            ."WHEN NULLIF(TRIM({$alias}.shopify_product_id), '') IS NOT NULL THEN CONCAT('shopify-product:', LOWER(TRIM({$alias}.shopify_product_id))) "
            ."WHEN NULLIF(TRIM(COALESCE({$alias}.tongtu_product_name, {$alias}.product_title)), '') IS NOT NULL THEN CONCAT('product-name:', LOWER(TRIM(COALESCE({$alias}.tongtu_product_name, {$alias}.product_title)))) "
            ."ELSE CONCAT('sku:', COALESCE(NULLIF(LOWER(TRIM({$alias}.tongtu_product_code)), ''), NULLIF(LOWER(TRIM({$alias}.tongtu_sku)), ''), NULLIF(LOWER(TRIM({$alias}.shopify_sku)), ''), '__missing__')) END";
    }

    private function database(): Connection
    {
        return DB::connection(config('admin.database.connection') ?: config('database.default'));
    }
