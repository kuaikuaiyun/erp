    /**
     * @param array<string,mixed> $filters
     * @return array<string,mixed>
     */
    public function dashboard(array $filters, int $page = 1, int $perPage = 50): array
    {
        $allAlerts = $this->alertRows();
        $filtered = $this->filterRows($allAlerts, $filters);
        $total = $filtered->count();
        $lastPage = max(1, (int) ceil($total / $perPage));
        $page = min(max(1, $page), $lastPage);
        $offset = ($page - 1) * $perPage;

        $pageAlerts = $this->withStatuses($filtered->slice($offset, $perPage)->values(), true);

        return [
            'filters' => $filters,
            'kpis' => [
                ['key' => 'pending', 'value' => (string) $allAlerts->where('workflow_status_key', 'pending')->count(), 'note_key' => 'pending_note', 'tone' => 'warning'],
                ['key' => 'processing', 'value' => (string) $allAlerts->where('workflow_status_key', 'processing')->count(), 'note_key' => 'processing_note', 'tone' => 'warning'],
                ['key' => 'completed', 'value' => (string) $allAlerts->where('workflow_status_key', 'completed')->count(), 'note_key' => 'completed_note', 'tone' => 'primary'],
            ],
            'alerts' => $pageAlerts->all(),
            'pagination' => [
                'current_page' => $page,
                'last_page' => $lastPage,
                'per_page' => $perPage,
                'total' => $total,
                'from' => $total === 0 ? 0 : $offset + 1,
                'to' => min($offset + $perPage, $total),
            ],
        ];
    }

    /** @return array<string,mixed>|null */
    public function find(string $alertCode): ?array
    {
        $alert = $this->findAlertRow($alertCode, true);

        if ($alert === null) {
            return null;
        }

        $detailCacheKey = 'payment:product-alert-detail:v2:'.sha1((string) json_encode([
            'code' => (string) $alert['code'],
            'channel' => (string) ($alert['channel_type'] ?? ''),
            'orders' => (int) ($alert['eligible_order_count'] ?? 0),
            'disputes' => (int) ($alert['dispute_count'] ?? 0),
            'amount' => (float) ($alert['dispute_amount'] ?? 0),
        ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES));
        $detail = Cache::flexible(
            $detailCacheKey,
            [60, 300],
            fn (): array => $this->detailData($alert),
        );

        return [...$alert, ...$detail];
    }

    public function hasAlert(string $alertCode): bool
    {
        if (PaymentProductAlertAssignment::query()->where('alert_code', $alertCode)->exists()) {
            return true;
        }

        if (!preg_match('/^PW-(?:[PC]-)?(\d+)$/', $alertCode, $matches)) {
            return false;
        }

        // The alert code contains the representative order-item id generated by
        // the alert list. A status write only needs to verify that source record;
        // rebuilding all product metrics here turns a small write into a slow query.
        return $this->database()->table('logistics_order_items')
            ->where('id', (int) $matches[1])
            ->exists();
    }

    /** @return array{total:int,alerts:list<array<string,mixed>>} */
    public function workbenchAlerts(int $limit = 5): array
    {
        $alerts = $this->alertRows()
            ->where('workflow_status_key', '!=', 'completed')
            ->values();

        return [
            'total' => $alerts->count(),
            'alerts' => $alerts->take(max(1, $limit))->all(),
        ];
    }

    /** @return list<array<string,mixed>> */
    public function exportRows(): array
    {
        $metricRows = $this->cachedMetricRows(false);
        $productKeys = $metricRows->pluck('product_key')->filter()->unique()->values()->all();
        $latestPaidTimes = collect();
        if ($productKeys !== []) {
            $productKey = $this->productKeyExpression('export_items');
            $latestPaidTimes = $this->database()->table('logistics_order_items as export_items')
                ->join('logistics_orders as export_orders', 'export_orders.id', '=', 'export_items.logistics_order_id')
                ->whereIn(DB::raw($productKey), $productKeys)
                ->whereNotNull('export_orders.paid_at')
                ->selectRaw("{$productKey} as product_key")
                ->selectRaw('MAX(export_orders.paid_at) as latest_paid_at')
                ->groupByRaw($productKey)
                ->pluck('latest_paid_at', 'product_key');
        }

        return $metricRows->groupBy('product_key')->map(function (Collection $rows) use ($latestPaidTimes): array {
            $paypal = (array) ($rows->firstWhere('channel_type', 'paypal') ?? $rows->first());
            $card = (array) ($rows->firstWhere('channel_type', 'credit_card') ?? []);
            $paypal['paypal_delivered_order_count'] = (int) ($paypal['delivered_order_count'] ?? 0);
            $paypal['paypal_delivered_dispute_count'] = (int) ($paypal['delivered_dispute_order_count'] ?? 0);
            $paypal['paypal_delivered_dispute_rate'] = (float) ($paypal['delivered_dispute_rate'] ?? 0);
            $paypal['paypal_initial_refund_amount'] = (float) ($paypal['refund_amount'] ?? 0);
            $paypal['paypal_initial_received_amount'] = (float) ($paypal['received_amount'] ?? 0);
            $paypal['paypal_initial_refund_amount_rate'] = (float) ($paypal['refund_amount_rate'] ?? 0);
            $paypal['card_order_count'] = (int) ($card['eligible_order_count'] ?? 0);
            $paypal['card_complaint_count'] = (int) ($card['complaint_count'] ?? 0);
            $paypal['card_dispute_count'] = (int) ($card['dispute_count'] ?? 0);
            $paypal['card_dispute_rate'] = (float) ($card['dispute_rate'] ?? 0);
            $paypal['credit_card_delivered_order_count'] = (int) ($card['delivered_order_count'] ?? 0);
            $paypal['credit_card_delivered_dispute_count'] = (int) ($card['delivered_dispute_order_count'] ?? 0);
            $paypal['credit_card_delivered_dispute_rate'] = (float) ($card['delivered_dispute_rate'] ?? 0);
            $paypal['credit_card_initial_refund_amount'] = (float) ($card['refund_amount'] ?? 0);
            $paypal['credit_card_initial_received_amount'] = (float) ($card['received_amount'] ?? 0);
            $paypal['credit_card_initial_refund_amount_rate'] = (float) ($card['refund_amount_rate'] ?? 0);
            $latestPaidAt = $latestPaidTimes->get((string) ($paypal['product_key'] ?? ''));
            $paypal['latest_paid_at'] = $latestPaidAt
                ? Carbon::parse((string) $latestPaidAt, 'UTC')->timezone('Asia/Shanghai')->format('Y-m-d H:i')
                : '-';
            $paypal['export_dispute_alert'] = (float) ($paypal['dispute_rate'] ?? 0) > 3;
            $paypal['export_mismatch_alert'] = (float) ($paypal['description_mismatch_rate'] ?? 0) > 50;
            $paypal['is_alert'] = $paypal['export_dispute_alert'] || $paypal['export_mismatch_alert'];

            return $paypal;
        })->values()->all();
    }

    /** @return list<array<string,mixed>> */
    public function exportAlertRows(): array
    {
        return $this->alertRows()->values()->all();
    }

    /** @return array<string,array<string,mixed>> */
    public function metricsByProductKey(array $productKeys = [], array $filters = []): array
    {
        return $this->cachedMetricRows(false, $productKeys, $filters)->groupBy('product_key')->map(
            fn (Collection $rows): array => $rows->keyBy('channel_type')->all()
        )->all();
    }

    public function updateStatus(string $alertCode, string $status, string $operation, string $remark, AdminUser $actor): void
    {
        abort_unless(in_array($status, ['stopped', 'observing', 'backend_optimized', 'other', 'completed'], true), 422);

        $record = PaymentProductAlertAssignment::query()->firstOrNew(['alert_code' => $alertCode]);
        $previousStatus = $record->exists ? $this->normaliseResultStatus((string) $record->status) : 'pending';
        $record->status = $status;
        $record->save();

        PaymentProductAlertAssignmentLog::query()->create([
            'alert_code' => $alertCode,
            'event' => 'status_changed',
            'actor_id' => $actor->getKey(),
            'actor_name_snapshot' => $actor->name,
            'note' => json_encode([
                'from_status' => $previousStatus,
                'to_status' => $status,
                'operation' => $operation,
                'remark' => $remark,
            ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES),
        ]);

        $today = now('Asia/Shanghai');
        Cache::forget('payment:workbench:v2:'.$today->copy()->subDays(29)->format('Y-m-d').':'.$today->format('Y-m-d'));
    }

    /** @param array<string,mixed> $alert @return array<string,mixed> */
    private function detailData(array $alert): array
    {
        $database = $this->database();
        $productKey = $this->productKeyExpression('detail_items');
        $orderIds = $database->table('logistics_order_items as detail_items')
            ->join('logistics_orders as detail_orders', 'detail_orders.id', '=', 'detail_items.logistics_order_id')
            ->whereRaw("{$productKey} = ?", [$alert['product_key']])
            ->where(function ($query): void {
                $query->whereNull('detail_orders.subscription_origin_order_id')
                    ->orWhereRaw("TRIM(detail_orders.subscription_origin_order_id) = ''");
            })
            ->where(function ($query): void {
                $query->whereNotNull('detail_orders.paid_at')->orWhere('detail_orders.paid_amount_usd', '>', 0);
            })
            ->select('detail_orders.id')->distinct();
        if (($alert['channel_type'] ?? 'paypal') === 'credit_card') {
            $orderIds->whereRaw("CASE WHEN JSON_VALID(COALESCE(detail_orders.shopify_payload, '')) THEN JSON_SEARCH(JSON_EXTRACT(detail_orders.shopify_payload, '$.tags'), 'one', '%CreditCardBy%') ELSE NULL END IS NOT NULL");
        } else {
            $orderIds->whereNotNull('detail_orders.paypal_account_id')
                ->where('detail_orders.paypal_association_source', 'actual_transaction');
        }

        $orderTimeline = $database->table('logistics_orders as timeline_orders')
            ->whereIn('timeline_orders.id', clone $orderIds)
            ->selectRaw('MIN(timeline_orders.paid_at) as first_order_at')
            ->selectRaw('MAX(timeline_orders.paid_at) as last_order_at')
            ->first();
        $storeDistribution = $database->table('logistics_orders as store_orders')
            ->whereIn('store_orders.id', clone $orderIds)
            ->selectRaw("COALESCE(NULLIF(TRIM(store_orders.store_name), ''), '-') as store_name")
            ->selectRaw("COALESCE(NULLIF(TRIM(store_orders.operator_name), ''), '-') as operator_name")
            ->selectRaw('COUNT(DISTINCT store_orders.id) as order_count')
            ->selectRaw('MIN(store_orders.paid_at) as first_order_at')
            ->selectRaw('MAX(store_orders.paid_at) as last_order_at')
            ->groupBy('store_name', 'operator_name')
            ->orderByDesc('order_count')->orderByDesc('last_order_at')->get()
            ->map(fn (object $row): array => [
                'name' => (string) $row->store_name,
                'operator_name' => (string) $row->operator_name,
                'order_count' => (int) $row->order_count,
                'first_order_at' => $this->formatDateTime($row->first_order_at),
                'last_order_at' => $this->formatDateTime($row->last_order_at),
            ])->all();

        $disputes = $database->table('logistics_paypal_disputes')
            ->whereIn('logistics_order_id', clone $orderIds)
            ->selectRaw('logistics_order_id, COUNT(DISTINCT id) as dispute_count')
            ->selectRaw('GROUP_CONCAT(DISTINCT NULLIF(reason, \'\') SEPARATOR \' / \') as dispute_reasons')
            ->selectRaw('GROUP_CONCAT(DISTINCT NULLIF(status, \'\') SEPARATOR \' / \') as dispute_statuses')
            ->groupBy('logistics_order_id');

        $payments = $database->table('logistics_orders as orders')
            ->whereIn('orders.id', clone $orderIds)
            ->leftJoinSub($disputes, 'risk', 'risk.logistics_order_id', '=', 'orders.id')
            ->leftJoin('logistics_paypal_transactions as transaction', 'transaction.logistics_order_id', '=', 'orders.id')
            ->select(['orders.id', 'orders.shopify_order_number', 'orders.tongtu_order_number', 'orders.store_name', 'orders.paid_at', 'orders.paid_amount_usd'])
            ->selectRaw('MAX(transaction.payment_transaction_id) as transaction_id')
            ->selectRaw('MAX(transaction.status) as payment_status')
            ->selectRaw('MAX(COALESCE(risk.dispute_count, 0)) as dispute_count')
            ->selectRaw('MAX(risk.dispute_reasons) as dispute_reasons')
            ->selectRaw('MAX(risk.dispute_statuses) as dispute_statuses')
            ->groupBy('orders.id', 'orders.shopify_order_number', 'orders.tongtu_order_number', 'orders.store_name', 'orders.paid_at', 'orders.paid_amount_usd')
            ->orderByDesc('orders.paid_at')->limit(100)->get()
            ->map(static fn (object $row): array => [
                'order' => (string) ($row->shopify_order_number ?: $row->tongtu_order_number ?: $row->id),
                'store' => (string) ($row->store_name ?: '-'),
                'transaction_id' => (string) ($row->transaction_id ?: '-'),
                'amount' => (float) $row->paid_amount_usd,
                'payment_status' => (string) ($row->payment_status ?: '-'),
                'dispute_count' => (int) $row->dispute_count,
                'dispute_reasons' => (string) ($row->dispute_reasons ?: '-'),
                'dispute_statuses' => (string) ($row->dispute_statuses ?: '-'),
                'time' => $row->paid_at ? date('Y-m-d H:i', strtotime((string) $row->paid_at)) : '-',
            ])->all();

        $paymentEvents = $database->table('logistics_paypal_transactions')
            ->whereIn('logistics_order_id', clone $orderIds)
            ->orderByDesc('paid_at')->limit(100)->get()
            ->map(static fn (object $row): array => [
                'type' => 'payment', 'reference' => (string) ($row->payment_transaction_id ?: '-'),
                'related_reference' => (string) ($row->invoice_id ?: '-'), 'status' => (string) ($row->status ?: '-'),
                'amount' => (float) ($row->payment_amount_usd ?? $row->original_amount ?? 0),
                'reason' => (string) ($row->payment_subject ?: '-'),
                'time' => $row->paid_at ? date('Y-m-d H:i', strtotime((string) $row->paid_at)) : '-',
                'sort_time' => (string) ($row->paid_at ?: ''),
            ]);
        $refundEvents = $database->table('logistics_paypal_refunds')
            ->whereIn('logistics_order_id', clone $orderIds)
            ->orderByDesc('refunded_at')->limit(100)->get()
            ->map(static fn (object $row): array => [
                'type' => 'refund', 'reference' => (string) ($row->refund_transaction_id ?: '-'),
                'related_reference' => (string) ($row->original_transaction_id ?: '-'), 'status' => (string) ($row->status ?: '-'),
                'amount' => (float) ($row->refund_amount_usd ?? $row->original_amount ?? 0),
                'reason' => (string) ($row->refund_reason ?: '-'),
                'time' => $row->refunded_at ? date('Y-m-d H:i', strtotime((string) $row->refunded_at)) : '-',
                'sort_time' => (string) ($row->refunded_at ?: ''),
            ]);

        if (($alert['channel_type'] ?? 'paypal') === 'credit_card') {
            $paymentEvents = collect();
            $refundEvents = $database->table('logistics_credit_card_refunds')
                ->whereIn('logistics_order_id', clone $orderIds)->orderByDesc('last_imported_at')->limit(100)->get()
                ->map(static fn (object $row): array => [
                    'type' => 'refund', 'reference' => (string) ($row->refund_reference ?: '-'),
                    'related_reference' => (string) ($row->bill_number ?: '-'), 'status' => '-',
                    'amount' => (float) ($row->refund_amount_usd ?? 0), 'reason' => (string) ($row->refund_reason ?: '-'),
                    'time' => $row->last_imported_at ? date('Y-m-d H:i', strtotime((string) $row->last_imported_at)) : '-',
                    'sort_time' => (string) ($row->last_imported_at ?: ''),
                ]);
        }

        $logs = PaymentProductAlertAssignmentLog::query()->where('alert_code', $alert['code'])
            ->where('event', 'status_changed')->latest('created_at')->limit(100)->get()
            ->map(function (PaymentProductAlertAssignmentLog $log): array {
                $payload = json_decode((string) $log->note, true);
                $from = is_array($payload) ? (string) ($payload['from_status'] ?? 'pending') : 'pending';
                $to = is_array($payload) ? (string) ($payload['to_status'] ?? 'pending') : 'pending';
                $from = $this->normaliseResultStatus($from);
                $to = $this->normaliseResultStatus($to);
                return [
                    'from_status' => $from,
                    'to_status' => $to,
                    'operation' => is_array($payload) ? ($payload['operation'] ?? 'process') : 'process',
                    'remark' => is_array($payload) ? ($payload['remark'] ?? (string) $log->note) : (string) $log->note,
                    'actor' => (string) ($log->actor_name_snapshot ?: '-'),
                    'time' => $log->created_at ? $log->created_at->timezone('Asia/Shanghai')->format('Y-m-d H:i:s') : '-',
                ];
            })->all();

        return [
            'payments' => $payments,
            'payment_events' => $paymentEvents->merge($refundEvents)->sortByDesc('sort_time')->take(100)->values()->all(),
            'processing_logs' => $logs,
            'store_order_distribution' => $storeDistribution,
            'first_order_at' => $this->formatDateTime($orderTimeline?->first_order_at),
            'last_order_at' => $this->formatDateTime($orderTimeline?->last_order_at),
        ];
    }

    public static function disputeRate(int $eligibleOrders, int $disputeOrders): float
    {
        return $eligibleOrders > 0 ? round($disputeOrders / $eligibleOrders * 100, 2) : 0.0;
    }

    public static function qualifies(int $eligibleOrders, int $disputeOrders): bool
    {
        return $eligibleOrders >= self::MINIMUM_ORDER_COUNT
            && self::disputeRate($eligibleOrders, $disputeOrders) >= self::DISPUTE_RATE_THRESHOLD;
    }

    /** @return Collection<int,array<string,mixed>> */
    private function metricRows(bool $onlyQualified = true, array $productKeys = [], array $filters = []): Collection
    {
        $database = $this->database();
        $productKey = $this->productKeyExpression('items');
        $paidOrder = '(orders.paid_at IS NOT NULL OR COALESCE(orders.paid_amount_usd, 0) > 0)';
        $initialOrder = "(orders.subscription_origin_order_id IS NULL OR TRIM(orders.subscription_origin_order_id) = '')";

        // One row represents one product in one paid order. This is the key
        // de-duplication boundary: quantity does not increase the order count,
        // while an order containing several products belongs once to each one.
        $productOrders = $database->table('logistics_order_items as items')
            ->join('logistics_orders as orders', 'orders.id', '=', 'items.logistics_order_id')
            ->whereRaw($paidOrder)
            ->whereRaw($initialOrder)
            ->selectRaw("{$productKey} as product_key")
            ->addSelect('orders.id as order_id')
            ->selectRaw('MIN(items.id) as first_item_id')
            ->selectRaw('SUM(COALESCE(items.quantity, 0)) as unit_count')
            ->selectRaw('MAX(COALESCE(orders.paid_amount_usd, 0)) as paid_amount_usd')
            ->selectRaw('MAX(orders.paypal_account_id) as paypal_account_id')
            ->selectRaw('MAX(orders.paypal_association_source) as paypal_association_source')
            ->selectRaw('MAX(orders.shopify_payload) as shopify_payload')
            ->selectRaw('MAX(orders.logistics_status) as logistics_status')
            ->selectRaw('MAX(orders.paid_at) as paid_at')
            ->groupByRaw("{$productKey}, orders.id");
        $this->applyOrderPaidAtRange($productOrders, $filters);
        if (($filters['store'] ?? '') !== '') $productOrders->where('orders.store_name', $filters['store']);
        if ($productKeys !== []) {
            $productOrders->whereIn(DB::raw($productKey), array_values(array_unique($productKeys)));
        }

        $disputes = $database->table('logistics_paypal_disputes as dispute')
            ->whereNotNull('dispute.logistics_order_id')
            ->select(['dispute.logistics_order_id', 'dispute.logistics_paypal_account_id'])
            ->selectRaw('COUNT(DISTINCT dispute.id) as dispute_count')
            ->selectRaw("SUM(COALESCE(dispute.dispute_amount_usd, CASE WHEN UPPER(dispute.currency_code) = 'USD' THEN dispute.original_amount ELSE 0 END)) as dispute_amount")
            ->selectRaw("SUM(CASE WHEN UPPER(COALESCE(dispute.reason, '')) LIKE '%NOT_AS_DESCRIBED%' OR UPPER(COALESCE(dispute.reason, '')) LIKE '%MERCHANDISE_OR_SERVICE_NOT_AS_DESCRIBED%' THEN COALESCE(dispute.dispute_amount_usd, CASE WHEN UPPER(dispute.currency_code) = 'USD' THEN dispute.original_amount ELSE 0 END) ELSE 0 END) as description_mismatch_amount")
            ->groupBy('dispute.logistics_order_id', 'dispute.logistics_paypal_account_id');
        $this->applyPayPalEventDateFilters($disputes, $filters, 'dispute.dispute_created_at');

        $paypalRefunds = $database->table('logistics_paypal_refunds as refund')
            ->whereNotNull('refund.logistics_order_id')
            ->select(['refund.logistics_order_id', 'refund.logistics_paypal_account_id'])
            ->selectRaw('COUNT(DISTINCT refund.id) as refund_count')
            ->selectRaw("SUM(COALESCE(refund.refund_amount_usd, CASE WHEN UPPER(refund.currency_code) = 'USD' THEN refund.original_amount ELSE 0 END)) as refund_amount")
            ->groupBy('refund.logistics_order_id', 'refund.logistics_paypal_account_id');
        $this->applyPayPalEventDateFilters($paypalRefunds, $filters, 'refund.refunded_at');

        $reasonExpression = "LOWER(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(COALESCE(refund.refund_reason, ''), '（', ''), '）', ''), '(', ''), ')', ''), ' ', ''))";
        $reasonList = function (array $reasons) use ($database): string {
            return implode(', ', array_map(
                fn (string $reason): string => $database->getPdo()->quote(LogisticsCreditCardRefundReason::normalize($reason)),
                $reasons,
            ));
        };
        $alertReasons = $reasonList(LogisticsCreditCardRefundReason::ALERT);
        $serviceReasons = $reasonList(LogisticsCreditCardRefundReason::CUSTOMER_SERVICE);
        $disputeReasons = $reasonList(LogisticsCreditCardRefundReason::DISPUTE);
        $cardRisk = $database->table('logistics_credit_card_refunds as refund')
            ->select('refund.logistics_order_id')
            ->selectRaw("SUM(CASE WHEN {$reasonExpression} IN ({$alertReasons}) THEN 1 ELSE 0 END) as complaint_count")
            ->selectRaw("SUM(CASE WHEN {$reasonExpression} IN ({$serviceReasons}) THEN 1 ELSE 0 END) as refund_count")
            ->selectRaw("MAX(CASE WHEN {$reasonExpression} IN ({$serviceReasons}) THEN 1 ELSE 0 END) as refund_order_flag")
            ->selectRaw("SUM(CASE WHEN {$reasonExpression} IN ({$serviceReasons}) THEN COALESCE(refund.refund_amount_usd, 0) ELSE 0 END) as refund_amount")
            ->selectRaw("SUM(CASE WHEN {$reasonExpression} IN ({$disputeReasons}) THEN 1 ELSE 0 END) as dispute_count")
            ->selectRaw("SUM(CASE WHEN {$reasonExpression} IN ({$disputeReasons}) THEN COALESCE(refund.refund_amount_usd, 0) ELSE 0 END) as dispute_amount")
            ->groupBy('refund.logistics_order_id');

        $actualPayPal = "(product_orders.paypal_account_id IS NOT NULL AND product_orders.paypal_association_source = 'actual_transaction')";
        $creditCard = "(CASE WHEN JSON_VALID(COALESCE(product_orders.shopify_payload, '')) THEN JSON_SEARCH(JSON_EXTRACT(product_orders.shopify_payload, '$.tags'), 'one', '%CreditCardBy%') ELSE NULL END IS NOT NULL)";
        $payload = "LOWER(COALESCE(product_orders.shopify_payload, ''))";
        $yunhui = "({$creditCard} AND ({$payload} LIKE '%yunhui%' OR {$payload} LIKE '%云汇%'))";
        $qianhai = "({$creditCard} AND ({$payload} LIKE '%qianhai%' OR {$payload} LIKE '%oceanpayment%' OR {$payload} LIKE '%钱海%'))";

        $delivered = $database->getPdo()->quote(\App\Models\LogisticsOrder::LOGISTICS_DELIVERED);

        $rows = $database->query()->fromSub($productOrders, 'product_orders')
            ->join('logistics_order_items as first_item', 'first_item.id', '=', 'product_orders.first_item_id')
            ->leftJoinSub($disputes, 'paypal_disputes', function ($join): void {
                $join->on('paypal_disputes.logistics_order_id', '=', 'product_orders.order_id')
