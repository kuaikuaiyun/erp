<?php

namespace App\Console\Commands;

use App\Portals\Finance\FinanceSummaryProjection;
use App\Portals\Finance\FinanceSummaryDependencies;
use App\Portals\Finance\FinanceReportSnapshots;
use App\Portals\Finance\FinancePayPalSettlementProjection;
use App\Portals\Finance\Http\Controllers\FinanceController;
use App\Portals\Finance\FinanceWorkbookService;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Cache;

class RefreshFinanceSummaries extends Command
{
    protected $signature = 'finance:summaries:refresh';

    protected $description = 'Publish pending monthly finance summary projections';

    public function handle(FinanceWorkbookService $workbooks, FinanceSummaryProjection $projection, FinanceSummaryDependencies $dependencies, FinanceReportSnapshots $reports, FinanceController $controller, FinancePayPalSettlementProjection $paypalSettlement): int
    {
        $db = $workbooks->database();
        if (! $reports->runsInBackground()) {
            return self::SUCCESS;
        }

        $lockName = 'finance:summaries:refresh:'.$db->getDatabaseName();
        $mysql = in_array($db->getDriverName(), ['mysql', 'mariadb'], true);
        $lock = $mysql ? null : Cache::lock($lockName, 300);
        $pdo = $mysql ? $db->getPdo() : null;
        $sessionLock = hash('sha256', $lockName);
        if ($pdo !== null) {
            // A session lock disappears when the worker or MySQL connection exits.
            $acquire = $pdo->prepare('SELECT GET_LOCK(?, 0)');
            $acquire->execute([$sessionLock]);
            $acquired = (int) $acquire->fetchColumn() === 1;
            $acquire->closeCursor();
        } else {
            $acquired = $lock->get();
        }
        if (! $acquired) {
            return self::SUCCESS;
        }
        $executionLimit = (int) ini_get('max_execution_time');
        if ($executionLimit === 0 || $executionLimit > 900) {
            set_time_limit(900);
        }
        $memoryLimit = (string) ini_get('memory_limit');
        $memoryBytes = ini_parse_quantity($memoryLimit);
        $raisedLimit = $memoryBytes > 0 && $memoryBytes < 256 * 1024 ** 2
            && ini_set('memory_limit', '256M') !== false;
        try {
            $this->recordStage('处理依赖变更');
            $tracksRevisions = \App\Portals\Finance\FinanceSummaryTriggers::available($db);
            $failed = false;
            if ($tracksRevisions) {
                $dependencies->resolve($db);
            }
            // Register the standard month/channel screens before looking for
            // active work. Reports are therefore generated by the scheduler,
            // not by the first person who happens to open a menu or search.
            $reports->registerDefaultScopes($tracksRevisions ? 12 : 1);
            $this->recordStage('检查月份投影');
            // Materialize only months people are actively viewing. Once those
            // rows are ready, report snapshots aggregate the projection instead
            // of joining the raw payment, logistics and settlement ledgers.
            if ($tracksRevisions && ! $projection->usesSourceFiles()) {
                try {
                    $activeMonths = $db->table('finance_report_scopes')->where('used_at', '>=', now()->subDays(7))
                        ->whereIn('report', ['summary', 'losses', 'transactions'])->where('month', '<>', '')
                        ->selectRaw('month, MAX(used_at) AS last_used_at')->groupBy('month')
                        ->orderByDesc('last_used_at')->orderByDesc('month')->pluck('month');
                    $periods = $activeMonths->isEmpty() ? collect() : $db->table('finance_summary_periods')
                        ->whereIn('month', $activeMonths)->whereColumn('published', '<>', 'revision')->get()->groupBy('month');
                    foreach ($activeMonths as $activeMonth) {
                        $pending = $periods->get($activeMonth, collect());
                        if ($pending->isEmpty()) {
                            continue;
                        }
                        foreach ($pending as $period) {
                            $this->recordStage('生成 '.$period->month.' / '.$period->channel.' 月份投影');
                            $projection->refresh($period);
                        }
                        // A PayPal + credit-card month can already take minutes;
                        // continue with the next month on the next scheduler run.
                        break;
                    }
                } catch (\Throwable $exception) {
                    $this->recordStage('月份投影执行异常（'.$exception::class.'）');
                    report($exception);
                    $failed = true;
                }
            }
            // Summary snapshots do not depend on the separate PayPal list
            // projection. Publish them first so a changing PayPal import cannot
            // starve credit-card, Ye or Worldpay reports.
            if (! $failed) $this->recordStage('生成汇总快照');
            $reportsRefreshed = ! $failed && $reports->refresh($controller, $tracksRevisions);
            $paypalRefreshed = true;
            if ($tracksRevisions && ! $failed) {
                try {
                    $this->recordStage('生成 PayPal 结算明细投影');
                    $paypalRefreshed = $paypalSettlement->refresh();
                    if (! $paypalRefreshed) $this->recordStage('汇总阶段已执行；PayPal 投影待重试或处于冷却期');
                } catch (\Throwable $exception) {
                    $this->recordStage('PayPal 结算投影执行异常（'.$exception::class.'）');
                    report($exception);
                    $failed = true;
                }
            }
            if (! $failed && $paypalRefreshed) $this->recordStage($reportsRefreshed ? '本轮执行完成' : '汇总快照未完成，等待重试');
            return $reportsRefreshed && ! $failed && $paypalRefreshed ? self::SUCCESS : self::FAILURE;
        } catch (\Throwable $exception) {
            $this->recordStage('执行异常（'.$exception::class.'）');
            throw $exception;
        } finally {
            if ($pdo !== null) {
                try {
                    $release = $pdo->prepare('SELECT RELEASE_LOCK(?)');
                    $release->execute([$sessionLock]);
                    $release->closeCursor();
                } catch (\PDOException $exception) {
                    report($exception);
                }
            } else {
                $lock->release();
            }
            if ($raisedLimit && memory_get_usage(true) < $memoryBytes) {
                ini_set('memory_limit', $memoryLimit);
            }
            set_time_limit($executionLimit);
        }
    }

    private function recordStage(string $stage): void
    {
        try {
            Cache::put('finance:summaries:worker-status', [
                'stage' => $stage, 'at' => now('Asia/Shanghai')->format('Y-m-d H:i:s'),
            ], now()->addDays(2));
        } catch (\Throwable) {
            // Diagnostics must never prevent publication.
        }
    }
}
